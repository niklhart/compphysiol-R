test_that("dosing sets preserve complete schedules and collection validity", {
    bolus <- dosing(time = c(0, 2) [h], amount = 10 [mg])
    infusion <- dosing(time = 0 [h], rate = 5 [mg/h], duration = 2 [h])
    sets <- dosing_sets(control = dosing(), treated = bolus, infusion = infusion)
    expect_length(sets, 3)
    expect_identical(sets[["treated"]], bolus)
    expect_identical(sets["infusion"][[1]], infusion)
    expect_s3_class(sets[integer()], "compphysiol_dosing_sets")
    expect_identical(c(sets[1], sets[2:3]), sets)
    expect_error(dosing_sets(parameters()), "dosing objects")
    expect_error(dosing_sets(a = bolus, a = bolus), "unique")
    expect_error(dosing_sets(`1` = bolus), "positive whole")
    expect_error(sets[c(1, 1)], "unique")
    expect_error(sets["missing"], "unknown")
    expect_error(sets[NA_integer_], "NA")
    expect_error(sets[4], "unknown")
    expect_output(print(sets), "treated")
    expect_output(print(dosing_sets()), "none")
    expect_error(names(sets) <- c("a", "a", "b"), "unique")
    names(sets) <- c("a", "b", "c")
    sets[1] <- dosing_sets(a = infusion)
    expect_identical(sets[[1]], infusion)
    sets[[2]] <- dosing()
    expect_length(sets[[2]], 0)
    sets[[3]] <- NULL
    expect_length(sets, 2)
    expect_error(sets[[1]] <- parameters(), "Dosing")
    expect_error(sets[1] <- dosing_sets(a = bolus, a = infusion), "unique")
})

test_that("dosing sets broadcast and align without forming combinations", {
    base <- experiment(name = "protocol", dosing = dosing(time = 0, amount = 1))
    sets <- dosing_sets(low = dosing(time = 1, amount = 2), high = dosing(time = 2, amount = 3))
    replaced <- replace_dosing(base, sets)
    expect_identical(names(replaced), c("low", "high"))
    expect_equal(.experiment_entry(replaced, 2)$dosing$time, 2)
    added <- add_dosing(base, sets)
    expect_length(.experiment_entry(added, 1)$dosing, 2)
    aligned <- replace_dosing(replaced, sets[2:1])
    expect_identical(aligned, replaced)
    for (verb in list(add_dosing, replace_dosing)) {
        result <- verb(replaced, dosing_sets(ignored = dosing(time = 3, amount = 4)))
        expect_identical(names(result), names(replaced))
        expect_equal(tail(.experiment_entry(result, 2)$dosing$time, 1), 3)
    }
    expect_error(replace_dosing(replaced, dosing_sets(x = dosing(), y = dosing())), "identifiers")
    expect_error(replace_dosing(replaced, dosing_sets(dosing(), dosing(), dosing())), "length one or match")
    expect_identical(names(replace_dosing(base, dosing_sets(other = dosing()))), "protocol")
    expect_null(names(replace_dosing(base, dosing_sets(dosing(), dosing()))))
    unnamed <- replace_dosing(experiment(), dosing_sets(dosing(), dosing()))
    expect_equal(length(replace_dosing(unnamed, dosing_sets(dosing(), dosing()))), 2)
    expect_error(replace_dosing(experiment(start = 2), sets), "start")
    expect_error(replace_dosing(experiment(start = 0 [h]), sets), "units|unit-free")
    expect_length(replace_dosing(experiment(), dosing_sets()), 0)
    expect_length(replace_dosing(replaced[integer()], dosing_sets(dosing())), 0)
    expect_error(replace_dosing(replaced[integer()], sets), "length one or match")
})
